"""Generate contract artifacts from packages/contracts/tw_contracts/schema_src.py.

Writes:
  packages/contracts/tw_contracts/schemas/*.schema.json
  packages/contracts/tw_contracts/types.py          (Python TypedDicts)
  packages/contracts/ts/index.ts                     (TypeScript interfaces)
  packages/contracts/csharp/TinkerWink.Contracts.cs  (C# records for System.Text.Json)
Run with --check to fail if any file is out of date (used by tests/CI).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "packages" / "contracts"
sys.path.insert(0, str(PKG))
from tw_contracts import schema_src as S  # noqa: E402

HEADER = "AUTO-GENERATED by tools/codegen.py from schema_src.py. Do not edit."


def pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in s.replace("-", "_").split("_"))


class Gen:
    def __init__(self):
        self.named: dict[str, dict] = {}  # type name -> object schema
        self.order: list[str] = []

    def register(self, name: str, schema: dict):
        if name in self.named:
            return
        self.named[name] = schema
        for k, v in schema["properties"].items():
            self.walk(name + pascal(k), v)
        self.order.append(name)

    def walk(self, hint: str, s: dict):
        if s.get("type") == "object" and "properties" in s:
            self.register(s.get("title", hint), s)
        elif s.get("type") == "array":
            self.walk(hint + "Item", s["items"])
        elif isinstance(s.get("additionalProperties"), dict):
            self.walk(hint + "Value", s["additionalProperties"])

    # ---- type expressions
    def name_for(self, hint: str, s: dict) -> str:
        return s.get("title", hint)

    def py(self, hint, s):
        if "$ref" in s:
            return s["$ref"].split("/")[-1]
        if "enum" in s:
            return "Literal[" + ", ".join(json.dumps(e) for e in s["enum"]) + "]"
        t = s.get("type")
        if isinstance(t, list):
            return " | ".join(self.py(hint, {**s, "type": x}) for x in t)
        if t == "object":
            if "properties" in s:
                return self.name_for(hint, s)
            ap = s.get("additionalProperties")
            return f"dict[str, {self.py(hint + 'Value', ap) if isinstance(ap, dict) else 'Any'}]"
        if t == "array":
            return f"list[{self.py(hint + 'Item', s['items'])}]"
        return {"string": "str", "number": "float", "integer": "int", "boolean": "bool", "null": "None"}[t]

    def ts(self, hint, s):
        if "$ref" in s:
            return s["$ref"].split("/")[-1]
        if "enum" in s:
            return " | ".join(json.dumps(e) for e in s["enum"])
        t = s.get("type")
        if isinstance(t, list):
            return " | ".join(self.ts(hint, {**s, "type": x}) for x in t)
        if t == "object":
            if "properties" in s:
                return self.name_for(hint, s)
            ap = s.get("additionalProperties")
            return f"Record<string, {self.ts(hint + 'Value', ap) if isinstance(ap, dict) else 'unknown'}>"
        if t == "array":
            inner = self.ts(hint + "Item", s["items"])
            return f"Array<{inner}>"
        return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}[t]

    def cs(self, hint, s):
        if "$ref" in s:
            return s["$ref"].split("/")[-1]
        if "enum" in s:
            return "string"
        t = s.get("type")
        if isinstance(t, list):
            non_null = [x for x in t if x != "null"]
            base = self.cs(hint, {**s, "type": non_null[0]}) if len(non_null) == 1 else "System.Text.Json.JsonElement"
            return base + ("?" if "null" in t else "")
        if t == "object":
            if "properties" in s:
                return self.name_for(hint, s)
            ap = s.get("additionalProperties")
            return f"Dictionary<string, {self.cs(hint + 'Value', ap) if isinstance(ap, dict) else 'System.Text.Json.JsonElement'}>"
        if t == "array":
            return f"List<{self.cs(hint + 'Item', s['items'])}>"
        return {"string": "string", "number": "double", "integer": "long", "boolean": "bool"}[t]


def build():
    g = Gen()
    for n, d in S.DEFS.items():
        g.register(n, d)
    for n, d in S.DOCS.items():
        g.register(n, d)
    out: dict[Path, str] = {}
    for n in S.DOCS:
        out[PKG / "tw_contracts" / "schemas" / f"{n}.schema.json"] = json.dumps(S.full_schema(n), indent=2) + "\n"
    py = [f'"""{HEADER}"""', "from __future__ import annotations", "", "from typing import Any, Literal, TypedDict", ""]
    ts = [f"// {HEADER}", f'export const SCHEMA_VERSION = "{S.SCHEMA_VERSION}";', ""]
    cs = [f"// {HEADER}", "#nullable enable", "using System.Collections.Generic;", "using System.Text.Json.Serialization;", "",
          "namespace TinkerWink.Contracts", "{", f'    public static class SchemaInfo {{ public const string Version = "{S.SCHEMA_VERSION}"; }}', ""]
    for name in g.order:
        s = g.named[name]
        req = set(s.get("required", []))
        py.append(f"class {name}(TypedDict, total=False):")
        ts.append(f"export interface {name} {{")
        cs.append(f"    public sealed class {name}")
        cs.append("    {")
        for k, v in s["properties"].items():
            hint = name + pascal(k)
            py.append(f"    {k}: {g.py(hint, v)}{'  # required' if k in req else ''}")
            ts.append(f"  {k}{'' if k in req else '?'}: {g.ts(hint, v)};")
            ctype = g.cs(hint, v)
            if k not in req and not ctype.endswith("?"):
                ctype += "?"
            init = " = default!;" if not ctype.endswith("?") and ctype not in ("double", "long", "bool") else ""
            cs.append(f'        [JsonPropertyName("{k}")] public {ctype} {pascal(k)} {{ get; set; }}{init}')
        py.append("")
        py.append("")
        ts.append("}")
        ts.append("")
        cs.append("    }")
        cs.append("")
    cs.append("}")
    py.append(f'SCHEMA_VERSION = "{S.SCHEMA_VERSION}"')
    out[PKG / "tw_contracts" / "types.py"] = "\n".join(py).rstrip() + "\n"
    out[PKG / "ts" / "index.ts"] = "\n".join(ts).rstrip() + "\n"
    out[PKG / "csharp" / "TinkerWink.Contracts.cs"] = "\n".join(cs).rstrip() + "\n"
    return out


def main(argv):
    out = build()
    stale = []
    for p, text in out.items():
        if "--check" in argv:
            if not p.exists() or p.read_text("utf-8") != text:
                stale.append(str(p.relative_to(ROOT)))
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, "utf-8")
    if stale:
        print("out of date:", *stale, sep="\n  ")
        return 1
    print(("checked " if "--check" in argv else "wrote ") + str(len(out)) + " files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
